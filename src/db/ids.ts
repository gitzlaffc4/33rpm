import { randomBytes } from "node:crypto";

/**
 * UUIDv7 (RFC 9562): 48-bit Unix-ms timestamp + random bits. App-generated, text,
 * time-sortable, and identical across dialects, so rows can be copied between
 * SQLite and PostgreSQL with their IDs intact.
 */
export function uuidv7(now: number = Date.now()): string {
  const b = randomBytes(16);
  b[0] = (now / 2 ** 40) & 0xff;
  b[1] = (now / 2 ** 32) & 0xff;
  b[2] = (now >>> 24) & 0xff;
  b[3] = (now >>> 16) & 0xff;
  b[4] = (now >>> 8) & 0xff;
  b[5] = now & 0xff;
  b[6] = 0x70 | (b[6] & 0x0f); // version 7
  b[8] = 0x80 | (b[8] & 0x3f); // RFC 4122 variant
  const h = b.toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

export const newId = () => uuidv7();
